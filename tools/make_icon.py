"""Generates the Sift launcher icon: a photo being filed into three manila folders.

Run from the project root:  python tools/make_icon.py
It rewrites the adaptive icon's background, foreground and monochrome vector drawables.
"""
import math
import os

RES = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'res')

# Everything is drawn on the 108 x 108 adaptive icon canvas, then shrunk into the safe zone
SCALE, SHIFT_Y = 0.78, -1.5

BLUE, AMBER, CORAL = '#5B8DF8', '#FFC247', '#FF7B6B'
LEFT, RIGHT, BOTTOM = 23.0, 85.0, 92.0
ROUND = 2.2                      # corner radius of the folders
PHOTO = (57.0, 38.0, 31.0, 35.0, 9.0)   # centre x, centre y, width, height, tilt in degrees
FRAME = 2.6


def f(v):
    return ('%.2f' % v).rstrip('0').rstrip('.')


def path_of(points):
    return 'M' + ' L'.join('%s,%s' % (f(x), f(y)) for x, y in points) + ' Z'


def folder(top, tab_x):
    """One manila folder: a body with a tab whose shoulders slant into it."""
    body, tab = top, top - 7.5
    if tab_x <= LEFT + 4:
        return [(LEFT, tab), (tab_x + 17, tab), (tab_x + 23, body), (RIGHT, body), (RIGHT, BOTTOM), (LEFT, BOTTOM)]
    if tab_x + 23 >= RIGHT:
        return [(LEFT, body), (tab_x - 6, body), (tab_x, tab), (RIGHT, tab), (RIGHT, BOTTOM), (LEFT, BOTTOM)]
    return [(LEFT, body), (tab_x - 6, body), (tab_x, tab), (tab_x + 17, tab), (tab_x + 23, body),
            (RIGHT, body), (RIGHT, BOTTOM), (LEFT, BOTTOM)]


BACK, MIDDLE, FRONT = folder(46, 26.0), folder(55, 44.5), folder(65, 63.0)


def rounded(points, r=ROUND):
    """Path of a polygon with every corner rounded. Drawn as a plain fill, so it can be semi-transparent."""
    out = ''
    n = len(points)
    for i, (x, y) in enumerate(points):
        (ax, ay), (bx, by) = points[i - 1], points[(i + 1) % n]
        la, lb = math.hypot(ax - x, ay - y), math.hypot(bx - x, by - y)
        ra, rb = min(r, la / 2), min(r, lb / 2)
        start = (x + (ax - x) / la * ra, y + (ay - y) / la * ra)
        end = (x + (bx - x) / lb * rb, y + (by - y) / lb * rb)
        out += '%s%s,%s Q%s,%s %s,%s ' % ('M' if i == 0 else 'L', f(start[0]), f(start[1]), f(x), f(y), f(end[0]), f(end[1]))
    return out + 'Z'


def rounded_rect(x, y, w, h, r):
    return ('M%s,%s H%s A%s,%s 0 0 1 %s,%s V%s A%s,%s 0 0 1 %s,%s H%s A%s,%s 0 0 1 %s,%s V%s A%s,%s 0 0 1 %s,%s Z'
            % (f(x + r), f(y), f(x + w - r), f(r), f(r), f(x + w), f(y + r), f(y + h - r), f(r), f(r), f(x + w - r), f(y + h),
               f(x + r), f(r), f(r), f(x), f(y + h - r), f(y + r), f(r), f(r), f(x + r), f(y)))


def circle(cx, cy, r):
    return 'M%s,%s A%s,%s 0 1 0 %s,%s A%s,%s 0 1 0 %s,%s Z' % (f(cx - r), f(cy), f(r), f(r), f(cx + r), f(cy), f(r), f(r), f(cx - r), f(cy))


cx, cy, pw, ph, tilt = PHOTO
px, py = cx - pw / 2, cy - ph / 2
ix, iy, iw, ih = px + FRAME, py + FRAME, pw - 2 * FRAME, ph - 2 * FRAME
PRINT = rounded_rect(px, py, pw, ph, 4.2)
WINDOW = rounded_rect(ix, iy, iw, ih, 2.2)
SUN = circle(ix + iw * .72, iy + ih * .28, min(iw, ih) * .12)
HILL_BACK = path_of([(ix, iy + ih), (ix + iw * .36, iy + ih * .44), (ix + iw * .58, iy + ih * .74),
                     (ix + iw * .74, iy + ih * .56), (ix + iw, iy + ih)])
HILL_FRONT = path_of([(ix, iy + ih), (ix + iw * .22, iy + ih * .68), (ix + iw * .5, iy + ih)])


def tilted_corners(grow):
    """Corners of the tilted print, grown by [grow], going anticlockwise on screen."""
    a = math.radians(tilt)
    out = []
    for dx, dy in [(-1, -1), (-1, 1), (1, 1), (1, -1)]:
        x, y = dx * (pw / 2 + grow), dy * (ph / 2 + grow)
        out.append((cx + x * math.cos(a) - y * math.sin(a), cy + x * math.sin(a) + y * math.cos(a)))
    return out


HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icon.py. Edit that script, not this file. -->\n'
OPEN = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"%s\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n')
GROUP = ('    <group\n        android:pivotX="54"\n        android:pivotY="54"\n'
         '        android:scaleX="%s"\n        android:scaleY="%s"\n        android:translateY="%s">\n' % (SCALE, SCALE, f(SHIFT_Y)))


def shape(d, fill, pad, alpha=None, stroke=None, stroke_width=None, even_odd=False, name=None):
    sp = ' ' * pad
    out = '%s<path\n' % sp
    if name:
        out += '%s    android:name="%s"\n' % (sp, name)
    out += '%s    android:fillColor="%s"\n' % (sp, fill)
    if alpha is not None:
        out += '%s    android:fillAlpha="%s"\n' % (sp, alpha)
        if stroke:
            out += '%s    android:strokeAlpha="%s"\n' % (sp, alpha)
    if stroke:
        out += ('%s    android:strokeColor="%s"\n%s    android:strokeWidth="%s"\n%s    android:strokeLineJoin="round"\n'
                % (sp, stroke, sp, f(stroke_width), sp))
    if even_odd:
        out += '%s    android:fillType="evenOdd"\n' % sp
    return out + '%s    android:pathData="%s" />\n' % (sp, d)


def tilted(body, pad):
    sp = ' ' * pad
    return ('%s<group\n%s    android:pivotX="%s"\n%s    android:pivotY="%s"\n%s    android:rotation="%s">\n%s%s</group>\n'
            % (sp, sp, f(cx), sp, f(cy), sp, f(tilt), body, sp))


def folder_shape(points, colour, pad, alpha=None):
    return shape(rounded(points), colour, pad, alpha=alpha)


# ---- colour foreground ----
picture = ('            <group>\n                <clip-path android:pathData="%s" />\n' % WINDOW
           + shape(WINDOW, '#CFE3FF', 16) + shape(SUN, '#FFAE1A', 16)
           + shape(HILL_BACK, '#6FCB8C', 16) + shape(HILL_FRONT, '#3FAE6A', 16) + '            </group>\n')
# The print is white on a white background, so this outline is all that separates the two
print_ = shape(PRINT, '#FFFFFF', 12, stroke='#8E9FD9', stroke_width=1.4) + picture
foreground = (HEAD + OPEN % '' + GROUP + folder_shape(BACK, BLUE, 8) + tilted(print_, 8)
              + folder_shape(MIDDLE, AMBER, 8) + folder_shape(FRONT, CORAL, 8) + '    </group>\n</vector>\n')

# ---- background ----
background = HEAD + OPEN % '' + shape('M0,0h108v108h-108z', '#FFFFFF', 4) + '</vector>\n'

# ---- themed (monochrome) version ----
# Same geometry as the colour icon. A themed icon has one colour, so white becomes "empty", the
# picture and the print's border are solid, and the three folders differ by opacity instead of hue.
#
# Semi-transparent shapes that overlap add up and show whatever is behind them. So nothing overlaps
# here: every shape is clipped to the part of it that is actually visible in the colour icon.
EVERYTHING = 'M0,0 H108 V108 H0 Z'


def outside(points, r=ROUND):
    """Clip path for "everywhere except this shape": the shape is traced backwards to punch a hole."""
    return EVERYTHING + ' ' + rounded(list(reversed(points)), r)


def clipped(clip, body, pad):
    sp = ' ' * pad
    return '%s<group>\n%s    <clip-path android:pathData="%s" />\n%s%s</group>\n' % (sp, sp, clip, body, sp)


def lowered(points, by):
    """A folder with its top edge moved down a little. Used as a hole, it lets the shape behind reach
    slightly under the folder, so no hairline of background shows where the two meet."""
    return [(x, y + by) for x, y in points[:-2]] + points[-2:]


# tilted_corners runs anticlockwise, so it is reversed here to let outside() reverse it back.
# The hole is smaller than the print, so the back folder ends under the print's solid border
print_outline = list(reversed(tilted_corners(-1.3)))
mono_print = (shape(PRINT + ' ' + WINDOW, '#000000', 24, even_odd=True)
              + '                        <group>\n                            <clip-path android:pathData="%s" />\n' % WINDOW
              + shape(SUN, '#000000', 28) + shape(HILL_BACK, '#000000', 28) + shape(HILL_FRONT, '#000000', 28)
              + '                        </group>\n')
monochrome = (HEAD + OPEN % '' + GROUP
              # back folder: hidden by the print, the middle folder and the front folder
              + clipped(outside(print_outline, 3.0),
                        clipped(outside(lowered(MIDDLE, 0.25)),
                                clipped(outside(lowered(FRONT, 0.5)), folder_shape(BACK, '#000000', 20, alpha='0.45'), 16), 12), 8)
              # print: hidden by the middle and front folders
              + clipped(outside(lowered(MIDDLE, 0.3)), clipped(outside(lowered(FRONT, 0.5)), tilted(mono_print, 16), 12), 8)
              # middle folder: hidden by the front folder
              + clipped(outside(lowered(FRONT, 0.5)), folder_shape(MIDDLE, '#000000', 12, alpha='0.7'), 8)
              + folder_shape(FRONT, '#000000', 8)
              + '    </group>\n</vector>\n')

# ---- animated splash icon ----
# The base vector is the first frame. The animators bring every shape to the pose of the colour
# foreground, so the last frame is the launcher icon. Android 11 gets the still copy instead,
# because its splash shows the first frame without starting it.
# MainActivity keeps the splash up until this has played to the end, so every extra millisecond here
# is added to a fast start.
# The system starts the animation when it creates the splash window, which is when the launcher
# begins growing that window out of the icon (about 300 ms on the user's phone). Nothing moves for
# the first half of that, and the rest overlaps the end of the growth to keep the wait short.
LEAD = 150
STAND = 200                      # how long a folder takes to stand up
STAGGER = 40                     # gap between one folder and the next
PHOTO_AT, PHOTO_FOR = LEAD + 70, 380   # when the print starts falling and for how long
PHOTO_FADE = 150
PHOTO_FROM = (-12.0, 0.7, -12.0)  # start offset up, start scale, start tilt
DURATION = max(PHOTO_AT + PHOTO_FOR, LEAD + 2 * STAGGER + STAND)

# Every shape moves one way only, so no curve may pass its end value. It also keeps moving for most
# of its time, so the end of the animation the splash waits for doesn't look frozen.
EASE_OUT = 'M0,0 C0.5,1 0.89,1 1,1'
MASK = 36.0                      # radius of the splash screen's circular mask on the 108 canvas


def on_canvas(x, y):
    return 54 + (x - 54) * SCALE, 54 + (y - 54) * SCALE + SHIFT_Y


def photo_corners(up, scale, angle):
    a = math.radians(angle)
    for dx, dy in [(-1, -1), (-1, 1), (1, 1), (1, -1)]:
        x, y = dx * pw / 2, dy * ph / 2
        rx, ry = x * math.cos(a) - y * math.sin(a), x * math.sin(a) + y * math.cos(a)
        yield on_canvas(cx + rx * scale, cy + ry * scale + up)


def ease(curve, t):
    """Value of a one-segment cubic pathInterpolator at time t, found by bisection on x."""
    x1, y1, x2, y2 = [float(v) for v in curve.split('C')[1].replace(' 1,1', '').replace(',', ' ').split()]
    lo, hi = 0.0, 1.0
    for _ in range(40):
        s = (lo + hi) / 2
        x = 3 * (1 - s) ** 2 * s * x1 + 3 * (1 - s) * s ** 2 * x2 + s ** 3
        lo, hi = (s, hi) if x < t else (lo, s)
    return 3 * (1 - s) ** 2 * s * y1 + 3 * (1 - s) * s ** 2 * y2 + s ** 3


assert all(0 <= float(v) <= 1 for v in EASE_OUT.split('C')[1].replace(',', ' ').split()), 'curve overshoots'

# The splash is clipped to a circle, so no frame may push the print past its edge
for step in range(101):
    move = turn = ease(EASE_OUT, step / 100)
    up = PHOTO_FROM[0] * (1 - move)
    scale = PHOTO_FROM[1] + (1 - PHOTO_FROM[1]) * move
    angle = PHOTO_FROM[2] + (tilt - PHOTO_FROM[2]) * turn
    for x, y in photo_corners(up, scale, angle):
        assert math.hypot(x - 54, y - 54) <= MASK, 'print leaves the splash mask at %d%% of its fall' % step


def named(name, pad, attrs, body):
    sp = ' ' * pad
    lines = ''.join('%s    android:%s="%s"\n' % (sp, k, v) for k, v in [('name', name)] + attrs)
    return '%s<group\n%s>\n%s%s</group>\n' % (sp, lines[:-1], body, sp)


def standing(name, points, colour, pad):
    return named(name, pad, [('pivotX', '54'), ('pivotY', f(BOTTOM)), ('scaleY', '0')],
                 folder_shape(points, colour, pad + 4))


PHOTO_PARTS = ['print', 'window', 'sun', 'hill_back', 'hill_front']
# Every part of the print starts see-through and fades in as it falls
anim_print = (shape(PRINT, '#FFFFFF', 16, alpha='0', stroke='#8E9FD9', stroke_width=1.4, name='print')
              + '                <group>\n                    <clip-path android:pathData="%s" />\n' % WINDOW
              + shape(WINDOW, '#CFE3FF', 20, alpha='0', name='window') + shape(SUN, '#FFAE1A', 20, alpha='0', name='sun')
              + shape(HILL_BACK, '#6FCB8C', 20, alpha='0', name='hill_back')
              + shape(HILL_FRONT, '#3FAE6A', 20, alpha='0', name='hill_front') + '                </group>\n')

up0, scale0, tilt0 = PHOTO_FROM
anim_photo = named('photo_drop', 8, [('pivotX', f(cx)), ('pivotY', f(cy)), ('translateY', f(up0)),
                                     ('scaleX', f(scale0)), ('scaleY', f(scale0))],
                   named('photo_tilt', 12, [('pivotX', f(cx)), ('pivotY', f(cy)), ('rotation', f(tilt0))], anim_print))
anim_vector = (OPEN % '' + GROUP + standing('back', BACK, BLUE, 8) + anim_photo
               + standing('middle', MIDDLE, AMBER, 8) + standing('front', FRONT, CORAL, 8) + '    </group>\n</vector>\n')


def animator(prop, start, end, at, length, curve=None, kind='floatType'):
    out = ('<objectAnimator android:propertyName="%s" android:valueFrom="%s" android:valueTo="%s"'
           ' android:valueType="%s" android:startOffset="%d" android:duration="%d"' % (prop, start, end, kind, at, length))
    if curve is None:
        return out + ' android:interpolator="@android:interpolator/linear" />'
    return (out + '>\n    <aapt:attr name="android:interpolator"><pathInterpolator android:pathData="%s" /></aapt:attr>\n'
            '</objectAnimator>' % curve)


def target(name, animators):
    return ('    <target android:name="%s">\n        <aapt:attr name="android:animation">\n            <set>\n%s'
            '            </set>\n        </aapt:attr>\n    </target>\n'
            % (name, ''.join('                ' + a.replace('\n', '\n                ') + '\n' for a in animators)))


targets = ''
for i, name in enumerate(['back', 'middle', 'front']):
    at = LEAD + i * STAGGER
    targets += target(name, [animator('scaleY', 0, 1, at, STAND, EASE_OUT)])
targets += target('photo_drop', [animator('translateY', f(up0), 0, PHOTO_AT, PHOTO_FOR, EASE_OUT),
                                 animator('scaleX', f(scale0), 1, PHOTO_AT, PHOTO_FOR, EASE_OUT),
                                 animator('scaleY', f(scale0), 1, PHOTO_AT, PHOTO_FOR, EASE_OUT)])
targets += target('photo_tilt', [animator('rotation', f(tilt0), f(tilt), PHOTO_AT, PHOTO_FOR, EASE_OUT)])
for part in PHOTO_PARTS:
    fades = [animator('fillAlpha', 0, 1, PHOTO_AT, PHOTO_FADE)]
    if part == 'print':
        fades.append(animator('strokeAlpha', 0, 1, PHOTO_AT, PHOTO_FADE))
    targets += target(part, fades)

indented = ''.join('        ' + line + '\n' if line else '\n' for line in anim_vector.rstrip('\n').split('\n'))
animated = (HEAD + '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt">\n    <aapt:attr name="android:drawable">\n'
            + indented.replace('<vector xmlns:android="http://schemas.android.com/apk/res/android"', '<vector')
            + '    </aapt:attr>\n' + targets + '</animated-vector>\n')

adaptive = (HEAD + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n')

for name, text in [('drawable/ic_launcher_foreground.xml', foreground), ('drawable/ic_launcher_background.xml', background),
                   ('drawable/ic_launcher_monochrome.xml', monochrome), ('mipmap-anydpi-v26/ic_launcher.xml', adaptive),
                   ('drawable/splash_icon.xml', foreground), ('drawable-v31/splash_icon.xml', animated),
                   ('values/splash.xml', HEAD + '<resources>\n    <integer name="splash_duration">%d</integer>\n</resources>\n' % DURATION)]:
    os.makedirs(os.path.dirname(os.path.join(RES, name)), exist_ok=True)
    with open(os.path.join(RES, name), 'w', encoding='utf-8', newline='\n') as out:
        out.write(text)
print('icon written, splash animation %d ms' % DURATION)
